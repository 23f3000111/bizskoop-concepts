#!/usr/bin/env python3
"""Finds the faces in every site photo (OpenCV YuNet) and writes shared/js/faces.js:
   window.BZ_FACES = { "<photo name>": [[x, y, w, h], ...] }  (fractions of the image size).
ui.js uses the boxes to choose an object-position that never cuts a face, whatever the frame shape.
Run from the project root after tools/assets.py photos:  python -P -E tools/faces.py
The model (face_detection_yunet_2023mar.onnx, opencv_zoo) is cached in tools/.cache."""
import json
import site
from pathlib import Path

site.addsitedir(site.getusersitepackages())
import cv2  # noqa: E402
import numpy as np  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
PHOTOS = ROOT / 'site-a-clear-path' / 'assets' / 'img' / 'photos'
MODEL = ROOT / 'tools' / '.cache' / 'face_detection_yunet_2023mar.onnx'
OUT = ROOT / 'shared' / 'js' / 'faces.js'
MAX = 1280


def detect(path, detector):
    img = cv2.imdecode(np.fromfile(str(path), dtype=np.uint8), cv2.IMREAD_COLOR)
    h, w = img.shape[:2]
    s = min(1.0, MAX / max(w, h))
    small = cv2.resize(img, (round(w * s), round(h * s))) if s < 1 else img
    detector.setInputSize((small.shape[1], small.shape[0]))
    _, found = detector.detect(small)
    boxes = []
    for f in (found if found is not None else []):
        x, y, bw, bh, score = (float(v) for v in (f[0] / s, f[1] / s, f[2] / s, f[3] / s, f[14]))
        if score < 0.75 or bw < 0.02 * w:
            continue
        boxes.append([round(max(0, x) / w, 3), round(max(0, y) / h, 3), round(bw / w, 3), round(bh / h, 3)])
    return sorted(boxes, key=lambda b: -b[2] * b[3])


def main():
    detector = cv2.FaceDetectorYN.create(str(MODEL), '', (320, 320), 0.75, 0.3, 5000)
    faces = {}
    for p in sorted(PHOTOS.glob('*.webp')):
        faces[p.stem] = detect(p, detector)
        print(f'{p.stem:24s} {len(faces[p.stem])} face(s)')
    body = json.dumps(faces, separators=(',', ':'))
    OUT.write_text('/* Face boxes per photo [x, y, w, h] as fractions of the image. Generated by tools/faces.py, do not edit. */\n'
                   '(function (root) {\n'
                   f'  const FACES = {body};\n'
                   '  root.BZ_FACES = FACES;\n'
                   "  if (typeof module !== 'undefined' && module.exports) module.exports = FACES;\n"
                   "})(typeof window !== 'undefined' ? window : globalThis);\n", encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
