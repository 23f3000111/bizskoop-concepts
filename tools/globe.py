#!/usr/bin/env python3
"""Land dots for Concept B's globe: Natural Earth 110 m land (public domain) -> evenly spread points on land.
Run from the project root:  python -P -E tools/globe.py
Input: source-assets/geo/ne_110m_land.geojson. Output: site-b-gateway/assets/js/globe-dots.js
(window.BZ_GLOBE_DOTS = [lat, lng, lat, lng, ...])."""
import json
import math
import site
from pathlib import Path

site.addsitedir(site.getusersitepackages())
from PIL import Image, ImageDraw  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'source-assets' / 'geo' / 'ne_110m_land.geojson'
OUT = ROOT / 'site-b-gateway' / 'assets' / 'js' / 'globe-dots.js'
W, H = 1440, 720
N = 15000  # points on the whole sphere before keeping the land ones


def to_px(lng, lat):
    return ((lng + 180) / 360 * W, (90 - lat) / 180 * H)


def main():
    mask = Image.new('L', (W, H), 0)
    draw = ImageDraw.Draw(mask)
    for f in json.loads(SRC.read_text(encoding='utf-8'))['features']:
        g = f['geometry']
        polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
        for poly in polys:
            draw.polygon([to_px(x, y) for x, y in poly[0]], fill=255)
            for hole in poly[1:]:
                draw.polygon([to_px(x, y) for x, y in hole], fill=0)
    golden = math.pi * (3 - math.sqrt(5))
    dots = []
    for i in range(N):
        y = 1 - (i + 0.5) / N * 2
        lat = math.degrees(math.asin(y))
        lng = math.degrees((i * golden) % (2 * math.pi)) - 180
        if lat < -58:
            continue
        px, py = to_px(lng, lat)
        if mask.getpixel((min(W - 1, int(px)), min(H - 1, int(py)))):
            dots += [round(lat, 2), round(lng, 2)]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('/* Land dots for the globe. Natural Earth 110 m land (public domain). Generated by tools/globe.py. */\n'
                   f'window.BZ_GLOBE_DOTS = {json.dumps(dots, separators=(",", ":"))};\n', encoding='utf-8', newline='\n')
    print(len(dots) // 2, 'land dots ->', OUT.relative_to(ROOT))


if __name__ == '__main__':
    main()
